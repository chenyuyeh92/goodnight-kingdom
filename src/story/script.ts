/** 每個世界的第一關(w1-1 … w10-1)放開頭句;其他關沒有。 */
export function introWorldOf(level: LevelId): number | null {
  const m = /^w(\d+)-1$/.exec(level);
  return m ? Number(m[1]) : null;
}

